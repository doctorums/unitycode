-- echo_responses.echo_text — снимок текста эха на момент отклика.
--
-- echo_responses.echo_id — ON DELETE CASCADE от echoes. echoes живут
-- ECHO_RETENTION_DAYS (сейчас 5) — pruneOld в unitycode-echo.js стирает
-- старые записи, и вместе с ними каскадом улетает строка в echo_responses,
-- даже если узел-отклик (nodes) остаётся в Сети навсегда. Через 5 дней
-- терялась бы всякая память о том, НА ЧТО именно откликнулся узел —
-- сама ссылка ещё есть (echo_id), а то, на что она указывает, уже нет.
--
-- Решение — снимок, не перессылка: текст эха копируется в echo_responses
-- в момент записи отклика (unitycode-write.js, recordEchoResponse), а не
-- достаётся через join к echoes по требованию. echo_id остаётся — пока
-- оригинал жив, полезен для сверки; когда его не станет, echo_text —
-- единственное, что расскажет, что именно всколыхнуло этот узел.
--
-- НЕ ПРИМЕНЯТЬ автоматически. Применяет Витя вручную через Supabase,
-- после явного «да» (получено 25.08).
-- ═══════════════════════════════════════════════════════════════════════════

alter table echo_responses add column if not exists echo_text text;

