-- Слой наблюдаемости, миграция 2 из 3 — таблица настроек.
--
-- Зачем. Единственный источник правды для порогов, коэффициентов и флагов
-- режимов. Воркеры читают её вместо зашитых констант: новая возможность =
-- новый ключ, без правки кода и без передеплоя. Для проекта, где деплой —
-- это ручная заливка файла в дашборд, разница существенная.
--
-- schema_version на каждой строке — тем же приёмом, что уже стоит в events:
-- форму value для отдельного ключа можно менять, не ломая читателей.
--
-- Порядок: после observability_1_connection_weight.sql, до
-- observability_3_snapshots.sql.
--
-- НЕ ПРИМЕНЯТЬ автоматически. Применяет Витя вручную через Supabase,
-- после явного «да».
-- ═══════════════════════════════════════════════════════════════════════════

create table if not exists public.settings (
  key            text primary key,
  value          jsonb not null,
  schema_version integer not null default 1,
  description    text,
  updated_at     timestamptz not null default now()
);

-- RLS обязателен. Дефолтные привилегии схемы public в этом проекте выдают
-- anon полный CRUD на любую новую таблицу (проверено: anon=arwdDxtm), а
-- анонимный ключ лежит открытым текстом в исходнике страницы. RLS здесь —
-- единственный замок. Все девять существующих таблиц проекта её имеют.
alter table public.settings enable row level security;

-- Чтение публичное: конфигурация не секрет, её читают воркеры и фронтенд.
drop policy if exists settings_read_all on public.settings;
create policy settings_read_all on public.settings for select using (true);

-- Политик на insert/update/delete НЕТ намеренно: при включённой RLS
-- отсутствие политики = запрет для anon, а service_role обходит RLS.
-- Это железное правило 6 — писать может только сервис-ключ.

comment on table public.settings is
