-- echo_runs — диагностический журнал прогонов unitycode-echo. Не про сами
-- новости (это echoes), а про то, что происходило во время сбора: сколько
-- источников обошли, сколько упёрлось в лимит подзапросов, сколько вставили.
--
-- Причина: ручной прогон через диагностический fetch() либо уходит в фон
-- (full=1, ответ без сводки), либо ждёт в браузере (full=1&wait=1) — а на
-- мобильной сети долгое ожидание браузер обрывает сам, показывая «нет
-- соединения», хотя воркер на сервере всё равно доработал. Вместо того чтобы
-- пытаться дотащить сводку до браузера, воркер сам пишет её сюда в конце
-- КАЖДОГО прогона (и cron, и ручного) — а дальше сводку смотрят через SQL,
-- без всякой зависимости от того, жив ли ещё браузер пользователя.
--
-- Не связана с echoes ничем, кроме факта происхождения из одного воркера.
-- Публичного доступа не нужно — ни карта, ни другие страницы её не читают.
-- ═══════════════════════════════════════════════════════════════════════════

create table if not exists echo_runs (
  id uuid primary key default gen_random_uuid(),
  ran_at timestamptz not null default now(),
  summary jsonb not null
);

create index if not exists echo_runs_ran_at_idx on echo_runs (ran_at desc);

alter table echo_runs enable row level security;
-- Политик для anon нет намеренно — таблица только для диагностики через
-- сервисный ключ/SQL, наружу (браузер, карта) ничего не отдаём.

